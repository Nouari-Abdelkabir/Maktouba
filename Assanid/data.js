const nodes = [];
const edges = [];

function addNode(id, label, type) {
    nodes.push({ id: id, label: label, type: type });
}
function addEdge(source, target) {
    edges.push({ source: source, target: target, type: "silsila" });
}

// دالة توليد الطرق الوهمية (للباقين)
function generateDummyRoutes(parentId, prefix, count) {
    for (let i = 1; i <= count; i++) {
        const routeId = `${prefix}_r${i}`;
        addNode(routeId, `طريق ${i}`, "route_num");
        addEdge(parentId, routeId);

        const sheikhId = `${routeId}_sheikh`;
        addNode(sheikhId, `شيخ سيضاف قريبا ${i}`, "other");
        addEdge(routeId, sheikhId);

        const bookId = `${routeId}_book`;
        addNode(bookId, `كتاب سيضاف قريبا ${i}`, "book");
        addEdge(sheikhId, bookId);
    }
}

// دالة توليد الطرق الحقيقية (تستخدم مصفوفة الأسماء)
// دالة توليد الطرق الحقيقية (تستخدم مصفوفة الأسماء)
function generateRealRoutes(parentId, prefix, routesArray) {
    routesArray.forEach((route, index) => {
        const routeNum = index + 1;
        const routeId = `${prefix}_r${routeNum}`;
        addNode(routeId, `طريق ${routeNum}`, "route_num");
        addEdge(parentId, routeId);
        
        let previousNode = routeId;
        route.forEach((person, pIndex) => {
            const personId = `${routeId}_p${pIndex}`;
            
             // 1. هل هذه العقدة عبارة عن كتاب؟
            const isBook = (pIndex === route.length - 1) || 
                           /^(من كتاب|كتاب|من )/.test(person.trim());
            
            // 2. هل هذه العقدة هي "صاحب الكتاب"؟ (أي أن الشخص الذي بعدها هو كتاب)
            // نتحقق مما إذا كان العنصر التالي في المصفوفة يبدأ بـ "من كتاب" أو "من "
            let isBookAuthor = false;
            if (pIndex < route.length - 1) {
                const nextPerson = route[pIndex + 1];
                if (/^(من كتاب|كتاب|من )/.test(nextPerson.trim())) {
                    isBookAuthor = true;
                }
            }

            // تحديد النوع النهائي
            let pType = "other";
            if (isBook) pType = "book";
            else if (isBookAuthor) pType = "book_author";

            addNode(personId, person, pType);
            addEdge(previousNode, personId);
            previousNode = personId;
        });
    });
}

