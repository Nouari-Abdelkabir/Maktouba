// 3. بناء الشجرة (القالب الرئيسي)
// ============================================================
function buildQari(qariId, qariName, rawisData) {
    addNode(qariId, qariName, "qari");
    addEdge("middle", qariId);

    rawisData.forEach((rawiData, rIndex) => {
        const rawiId = `${qariId}_rawi${rIndex + 1}`;
        addNode(rawiId, rawiData.name, "rawi");
        addEdge(qariId, rawiId);

        rawiData.turuq.forEach((tariqData, tIndex) => {
            const tariqId = `${rawiId}_tariq${tIndex + 1}`;
            addNode(tariqId, tariqData.name, "tariq");
            addEdge(rawiId, tariqId);

            const countBoxId = `${tariqId}_box`;
            addNode(countBoxId, `${tariqData.count} طريقاً`, "count_box");
            addEdge(tariqId, countBoxId);

            // 🌟 التحقق: هل هناك طرق حقيقية ممررة؟
            if (tariqData.realRoutes && tariqData.realRoutes.length > 0) {
                // إذا نعم، استخدم الطرق الحقيقية
                generateRealRoutes(countBoxId, tariqId, tariqData.realRoutes);
            } else {
                // إذا لا، ولّد طرقاً وهمية
                generateDummyRoutes(countBoxId, tariqId, tariqData.count);
            }
        });
    });
}

