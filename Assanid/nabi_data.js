const nabiNodes = [];
const nabiEdges = [];
const personMap = {}; 

function getOrCreatePerson(name, type) {
    if (!name || name.trim() === "" || name === "nan") return null;
    if (personMap[name]) return personMap[name];
    const id = `person_${name.replace(/\s+/g, '_').replace(/[^\u0621-\u064A0-9_]/g, '')}`;
    personMap[name] = id;
    nabiNodes.push({ id: id, label: name, type: type });
    return id;
}

function addNabiEdge(sourceId, targetId) {
    if (!sourceId || !targetId) return;
    if (!nabiEdges.some(e => e.source === sourceId && e.target === targetId)) {
        nabiEdges.push({ source: sourceId, target: targetId, type: "silsila" });
    }
}

